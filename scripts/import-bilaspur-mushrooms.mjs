async function ensureSystemUser(usersCollection) {
  const existing = await usersCollection.findOne({ email: "system@ecovigyan.org" });
  if (existing?._id) {
    return existing._id;
  }

  const now = new Date();
  const userDoc = {
    name: "System Import",
    username: "system",
    email: "system@ecovigyan.org",
    role: "admin",
    authProvider: "credentials",
    bio: "",
    points: 0,
    isVerified: true,
    isBanned: false,
    createdAt: now,
    updatedAt: now,
  };

  const insertResult = await usersCollection.insertOne(userDoc);
  return insertResult.insertedId;
}

async function run() {
  const client = new MongoClient(rawUri);
  await client.connect();

  try {
    const db = client.db(dbName);
    const usersCollection = db.collection("users");
    const mushroomsCollection = db.collection("mushrooms");

    const systemUserId = await ensureSystemUser(usersCollection);
    const now = new Date();

    const documents = coordinates.map(([latitude, longitude], index) => ({
      commonName: `Bilaspur Observation ${index + 1}`,
      description: "Imported coordinate-only observation for Bilaspur.",
      images: [],
      location: { latitude, longitude },
      submittedBy: new ObjectId(systemUserId),
      ecologicalRole: [],
      commonUses: [],
      status: "approved",
      reviewedBy: new ObjectId(systemUserId),
      approvedAt: now,
      createdAt: now,
      updatedAt: now,
    }));

    const result = await mushroomsCollection.insertMany(documents, { ordered: true });

    console.log(
      JSON.stringify(
        {
          insertedCount: result.insertedCount,
          firstInsertedId: result.insertedIds[0],
          dbName,
        },
        null,
        2
      )
    );
  } finally {
    await client.close();
  }
}

run().catch((error) => {
  console.error("Bilaspur import failed:", error);
  process.exit(1);
});
